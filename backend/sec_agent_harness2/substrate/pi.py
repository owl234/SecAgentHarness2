PI_ROOT_ENTRIES = ("AGENTS.md", ".pi", "scripts", "sub_agents", "mcp", ".mcp.json")
PI_BUILTIN_TOOLS = "read,bash,edit,write,grep,find,ls"

_PI_BRIDGE_TS = r"""// Auto-generated by SecAgentHarness2 PiSubstrate (`-e` runtime bridge).
// Bridges declarative `.pi/hooks.json` (c8), `sub_agents/*/AGENT.md` (c5),
// and `mcp/servers.json` (c9) into Pi's in-process ExtensionAPI without
// polluting the benchmark task workspace.
import * as fs from "node:fs";
import * as path from "node:path";
import { spawnSync } from "node:child_process";

function findHarnessRoot(cwd: string): string {
  const envRoot = process.env.SEC_AGENT_HARNESS2_PI_HARNESS_DIR || "";
  if (envRoot && fs.existsSync(envRoot)) {
    return envRoot;
  }
  return cwd;
}

function loadJsonFile(filePath: string): any {
  try {
    if (fs.existsSync(filePath)) {
      return JSON.parse(fs.readFileSync(filePath, "utf-8"));
    }
  } catch (_err) {
    // ignore malformed json at runtime
  }
  return null;
}

function matchesTool(matcher: string | undefined, toolName: string): boolean {
  if (!matcher || matcher === "*" || matcher.trim() === "") return true;
  const parts = matcher.split("|").map((s) => s.trim().toLowerCase()).filter(Boolean);
  const target = (toolName || "").toLowerCase();
  return parts.some((p) => p === "*" || p === target || target.includes(p));
}

function runHookCommands(
  entries: any[],
  toolName: string,
  payload: Record<string, any>,
  cwd: string
): Array<{ status: number; stdout: string; parsed: any }> {
  const results: Array<{ status: number; stdout: string; parsed: any }> = [];
  if (!Array.isArray(entries)) return results;
  for (const entry of entries) {
    if (!entry || typeof entry !== "object") continue;
    if (!matchesTool(entry.matcher, toolName)) continue;
    const hooks = Array.isArray(entry.hooks) ? entry.hooks : [];
    for (const h of hooks) {
      if (!h || h.type !== "command" || typeof h.command !== "string") continue;
      const timeoutMs = typeof h.timeout === "number" && h.timeout > 0 ? h.timeout * 1000 : 30000;
      const proc = spawnSync(h.command, {
        shell: true,
        cwd,
        input: JSON.stringify(payload),
        encoding: "utf-8",
        timeout: timeoutMs,
      });
      const stdout = (proc.stdout || "").trim();
      let parsed: any = null;
      if (stdout.startsWith("{") && stdout.endsWith("}")) {
        try {
          parsed = JSON.parse(stdout);
        } catch (_e) {
          parsed = null;
        }
      }
      results.push({ status: proc.status ?? 0, stdout, parsed });
    }
  }
  return results;
}

function parseSubAgents(rootDir: string): Record<string, { description: string; prompt: string }> {
  const out: Record<string, { description: string; prompt: string }> = {};
  const subDir = path.join(rootDir, "sub_agents");
  if (!fs.existsSync(subDir)) return out;
  try {
    for (const entry of fs.readdirSync(subDir, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue;
      const agentMd = path.join(subDir, entry.name, "AGENT.md");
      if (!fs.existsSync(agentMd)) continue;
      const raw = fs.readFileSync(agentMd, "utf-8");
      let description = `Subagent ${entry.name}`;
      let body = raw.trim();
      if (raw.startsWith("---\n")) {
        const endIdx = raw.indexOf("\n---\n", 4);
        if (endIdx !== -1) {
          const fm = raw.slice(4, endIdx);
          body = raw.slice(endIdx + 5).trim();
          for (const line of fm.split("\n")) {
            const idx = line.indexOf(":");
            if (idx !== -1) {
              const k = line.slice(0, idx).trim();
              const v = line.slice(idx + 1).trim().replace(/^['"]|['"]$/g, "");
              if (k === "description" && v) description = v;
            }
          }
        }
      }
      if (body) {
        out[entry.name] = { description, prompt: body };
      }
    }
  } catch (_err) {
    // ignore read errors
  }
  return out;
}

export default function (pi: any) {
  const cwd = process.cwd();
  const rootDir = findHarnessRoot(cwd);

  // 1. Declarative c8 hooks (`.pi/hooks.json`)
  const hooksCfg =
    loadJsonFile(path.join(cwd, ".pi", "hooks.json")) ||
    loadJsonFile(path.join(rootDir, ".pi", "hooks.json"));
  const hooksMap = hooksCfg && typeof hooksCfg.hooks === "object" ? hooksCfg.hooks : null;

  if (hooksMap) {
    if (Array.isArray(hooksMap.SessionStart)) {
      pi.on("session_start", async (_event: any, _ctx: any) => {
        runHookCommands(hooksMap.SessionStart, "*", { hook_event_name: "SessionStart", cwd }, cwd);
      });
    }
    if (Array.isArray(hooksMap.UserPromptSubmit)) {
      pi.on("before_agent_start", async (event: any, _ctx: any) => {
        const outs = runHookCommands(
          hooksMap.UserPromptSubmit,
          "*",
          { hook_event_name: "UserPromptSubmit", prompt: event?.prompt || "", cwd },
          cwd
        );
        const notes = outs
          .map((o) => (o.parsed?.reason || o.parsed?.additionalContext || o.stdout || "").trim())
          .filter(Boolean);
        if (notes.length > 0 && typeof event?.systemPrompt === "string") {
          return { systemPrompt: event.systemPrompt + "\n\n" + notes.join("\n") };
        }
        return undefined;
      });
    }
    if (Array.isArray(hooksMap.PreToolUse)) {
      pi.on("tool_call", async (event: any, _ctx: any) => {
        const toolName = event?.toolName || "";
        const outs = runHookCommands(
          hooksMap.PreToolUse,
          toolName,
          {
            hook_event_name: "PreToolUse",
            tool_name: toolName,
            tool_input: event?.input || {},
            cwd,
          },
          cwd
        );
        for (const o of outs) {
          if (o.parsed && o.parsed.decision === "block") {
            return {
              block: true,
              reason: o.parsed.reason || "Blocked by .pi/hooks.json PreToolUse hook",
            };
          }
        }
        return undefined;
      });
    }
    if (Array.isArray(hooksMap.PostToolUse)) {
      pi.on("tool_result", async (event: any, _ctx: any) => {
        const toolName = event?.toolName || "";
        const outs = runHookCommands(
          hooksMap.PostToolUse,
          toolName,
          {
            hook_event_name: "PostToolUse",
            tool_name: toolName,
            tool_input: event?.input || {},
            tool_response: event?.content || [],
            is_error: Boolean(event?.isError),
            cwd,
          },
          cwd
        );
        const extraTexts: string[] = [];
        for (const o of outs) {
          if (o.parsed && (o.parsed.decision === "block" || o.parsed.reason)) {
            extraTexts.push(`[Hook Feedback] ${o.parsed.reason || JSON.stringify(o.parsed)}`);
          }
        }
        if (extraTexts.length > 0 && Array.isArray(event?.content)) {
          return {
            content: [
              ...event.content,
              { type: "text", text: "\n" + extraTexts.join("\n") },
            ],
          };
        }
        return undefined;
      });
    }
    if (Array.isArray(hooksMap.Stop)) {
      pi.on("agent_end", async (_event: any, _ctx: any) => {
        runHookCommands(hooksMap.Stop, "*", { hook_event_name: "Stop", cwd }, cwd);
      });
    }
  }

  // 2. Subagent delegation tool (`c5`: `sub_agents/<name>/AGENT.md`)
  const subAgents = {
    ...parseSubAgents(rootDir),
    ...parseSubAgents(cwd),
  };
  const agentNames = Object.keys(subAgents);
  if (agentNames.length > 0 && typeof pi.registerTool === "function") {
    const summaryList = agentNames
      .map((n) => `- ${n}: ${subAgents[n].description}`)
      .join("\n");
    pi.registerTool({
      name: "subagent",
      label: "Delegate to Subagent",
      description: `Delegate a focused subtask to a specialized subagent defined in sub_agents/*/AGENT.md.\nAvailable subagents:\n${summaryList}`,
      parameters: {
        type: "object",
        properties: {
          agent: {
            type: "string",
            description: `Subagent name (${agentNames.join(", ")})`,
          },
          task: {
            type: "string",
            description: "Detailed task instructions for the subagent",
          },
        },
        required: ["agent", "task"],
      },
      async execute(_toolCallId: string, params: any) {
        const target = subAgents[params?.agent];
        if (!target) {
          return {
            content: [
              {
                type: "text",
                text: `Unknown subagent '${params?.agent}'. Available: ${agentNames.join(", ")}`,
              },
            ],
            isError: true,
          };
        }
        const piBin = process.env.SEC_AGENT_HARNESS2_PI_BIN || process.argv[1] || "pi";
        const args = [
          "-p",
          String(params?.task || ""),
          "--mode",
          "json",
          "--no-session",
          "--tools",
          "read,bash,edit,write,grep,find,ls",
          "--append-system-prompt",
          target.prompt,
        ];
        if (process.env.SEC_AGENT_HARNESS2_PI_PROVIDER) {
          args.push("--provider", process.env.SEC_AGENT_HARNESS2_PI_PROVIDER);
        }
        if (process.env.SEC_AGENT_HARNESS2_PI_ACTIVE_MODEL) {
          args.push("--model", process.env.SEC_AGENT_HARNESS2_PI_ACTIVE_MODEL);
        }
        const proc = spawnSync(piBin, args, {
          cwd,
          encoding: "utf-8",
          timeout: 600000,
        });
        let lastText = "";
        for (const line of (proc.stdout || "").split("\n")) {
          if (!line.trim().startsWith("{")) continue;
          try {
            const ev = JSON.parse(line);
            if (ev.type === "message_end" && ev.message?.role === "assistant") {
              for (const blk of ev.message.content || []) {
                if (blk.type === "text" && blk.text) lastText = blk.text;
              }
            }
          } catch (_e) {
            // ignore
          }
        }
        const output = lastText || (proc.stdout || "").trim() || (proc.stderr || "").trim();
        return {
          content: [{ type: "text", text: output || "(subagent completed with empty output)" }],
          details: { agent: params?.agent, status: proc.status ?? 0 },
        };
      },
    });
  }

  // 3. MCP Servers bridge (`c9`: `mcp/servers.json`)
  const mcpCfg =
    loadJsonFile(path.join(cwd, "mcp", "servers.json")) ||
    loadJsonFile(path.join(rootDir, "mcp", "servers.json")) ||
    loadJsonFile(path.join(cwd, ".mcp.json"));
  const mcpServers = mcpCfg && typeof mcpCfg.mcpServers === "object" ? mcpCfg.mcpServers : null;
  if (mcpServers && Object.keys(mcpServers).length > 0 && typeof pi.registerTool === "function") {
    const serverNames = Object.keys(mcpServers);
    pi.registerTool({
      name: "mcp_call",
      label: "Call MCP Server",
      description: `Interact with configured MCP servers (${serverNames.join(", ")}) from mcp/servers.json. Supports 'tools/list' and 'tools/call' over JSON-RPC.`,
      parameters: {
        type: "object",
        properties: {
          server: {
            type: "string",
            description: `MCP server name (${serverNames.join(", ")})`,
          },
          method: {
            type: "string",
            description: "JSON-RPC method: 'tools/list' or 'tools/call'",
          },
          tool_name: {
            type: "string",
            description: "Tool name when method is 'tools/call'",
          },
          arguments: {
            type: "object",
            description: "Tool arguments object when method is 'tools/call'",
          },
        },
        required: ["server", "method"],
      },
      async execute(_toolCallId: string, params: any) {
        const srv = mcpServers[params?.server];
        if (!srv) {
          return {
            content: [
              {
                type: "text",
                text: `Unknown MCP server '${params?.server}'. Available: ${serverNames.join(", ")}`,
              },
            ],
            isError: true,
          };
        }
        const rpcMethod = params?.method || "tools/list";
        const rpcParams =
          rpcMethod === "tools/call"
            ? { name: params?.tool_name || "", arguments: params?.arguments || {} }
            : {};
        const initReq = JSON.stringify({
          jsonrpc: "2.0",
          id: 1,
          method: "initialize",
          params: {
            protocolVersion: "2024-11-05",
            capabilities: {},
            clientInfo: { name: "pi-harness2-bridge", version: "1.0.0" },
          },
        });
        const callReq = JSON.stringify({
          jsonrpc: "2.0",
          id: 2,
          method: rpcMethod,
          params: rpcParams,
        });
        if (srv.command) {
          const srvArgs = Array.isArray(srv.args) ? srv.args.map(String) : [];
          const proc = spawnSync(srv.command, srvArgs, {
            cwd,
            env: { ...process.env, ...(srv.env || {}) },
            input: initReq + "\n" + callReq + "\n",
            encoding: "utf-8",
            timeout: 60000,
          });
          const out = (proc.stdout || "").trim() || (proc.stderr || "").trim();
          return {
            content: [{ type: "text", text: out || "(empty MCP response)" }],
            details: { server: params?.server, status: proc.status ?? 0 },
          };
        }
        return {
          content: [{ type: "text", text: `Remote MCP server URL: ${srv.url || "unknown"}` }],
          details: { server: params?.server },
        };
      },
    });
  }
}
"""


def find_pi_binary() -> Path:
    """Find the project-local Pi Coding Agent binary or explicit override."""
    custom = (
        os.environ.get("SEC_AGENT_HARNESS2_PI_BIN")
        or os.environ.get("SEC_AGENT_HARNESS2_PI_PATH")
        or os.environ.get("HARNESS2_PI_BIN")
        or os.environ.get("HARNESS2_PI_PATH")
    )
    if custom:
        p = Path(custom)
        if p.is_file() and os.access(p, os.X_OK):
            return p

    wrapper = config.PI_DIST / "bin" / "pi"
    if wrapper.is_file() and os.access(wrapper, os.X_OK):
        return wrapper

    if config.PI_BIN.is_file() and os.access(config.PI_BIN, os.X_OK):
        return config.PI_BIN

    which_bin = shutil.which("pi")
    if which_bin and os.access(which_bin, os.X_OK):
        return Path(which_bin)

    return config.PI_BIN


def write_pi_bridge_extension(dest_dir: Path) -> Path:
    """Write the zero-pollution runtime bridge extension for `pi -e <path>`."""
    dest_dir.mkdir(parents=True, exist_ok=True)
    bridge_file = dest_dir / "harness2_bridge.ts"
    bridge_file.write_text(_PI_BRIDGE_TS, encoding="utf-8")
    return bridge_file


def _needs_bridge_extension(root: Path | None) -> bool:
    """Return True if `root` contains `c5` subagents, declarative `c8` `.pi/hooks.json`, or `c9` MCP."""
    if root is None or not root.is_dir():
        return False
    if (root / ".pi" / "hooks.json").is_file():
        return True
    if (root / "mcp" / "servers.json").is_file() or (root / ".mcp.json").is_file():
        return True
    sub_dir = root / "sub_agents"
    if sub_dir.is_dir():
        for child in sub_dir.iterdir():
            if child.is_dir() and (child / "AGENT.md").is_file():
                return True
    return False


def mcp_config_json(harness_dir: Path | None) -> str:
    """Return a compact JSON string from `mcp/servers.json` if present."""
    if harness_dir is None:
        return ""
    mcp_path = Path(harness_dir) / "mcp" / "servers.json"
    if not mcp_path.is_file():
        return ""
    try:
        doc = json.loads(mcp_path.read_text(encoding="utf-8", errors="replace"))
    except json.JSONDecodeError:
        return ""
    servers = doc.get("mcpServers") if isinstance(doc, dict) else None
    if not isinstance(servers, dict) or not servers:
        return ""
    return json.dumps({"mcpServers": servers}, ensure_ascii=False)


class PiSubstrate:
    """Pi Coding Agent (`@mariozechner/pi-coding-agent`) behind the Substrate interface."""

    name = "pi"

    def __init__(self, launcher: Launcher | None = None):
        self._launcher = launcher

    def surface(self) -> SurfaceSpec:
        return PI_SURFACE

    def materialise(self, tree_dir: Path, spec, ctx: Mapping[str, str]) -> Install:
        """Stage the `pi_root` entries for a copy to the workspace root."""
        if spec.install_mode != "pi_root":
            raise ValueError(
                f"install_mode {spec.install_mode!r} is not valid for PiSubstrate; "
                f"this substrate requires 'pi_root'"
            )
        tree_dir = Path(tree_dir)
        if not HT.is_tree(PI_SURFACE, tree_dir):
            raise ValueError(f"{tree_dir} is not a valid pi harness tree (no AGENTS.md)")

        staged = Path(tempfile.mkdtemp(prefix="adapt-pi-root-"))
        try:
            for entry in PI_ROOT_ENTRIES:
                src = tree_dir / entry
                if not src.exists():
                    continue
                dst = staged / entry
                if src.is_dir():
                    shutil.copytree(src, dst)
                else:
                    shutil.copy2(src, dst)

            for key, body in ctx.items():
                if key.startswith("file:"):
                    rel = HT.normalize_rel(key[len("file:") :])
                    p = staged / rel
                    p.parent.mkdir(parents=True, exist_ok=True)
                    p.write_text(body, encoding="utf-8")

            mcp_raw = mcp_config_json(staged)
            if mcp_raw:
                (staged / ".mcp.json").write_text(
                    json.dumps(json.loads(mcp_raw), indent=2, ensure_ascii=False) + "\n",
                    encoding="utf-8",
                )

            bridge_path = write_pi_bridge_extension(staged / "_pi_runtime")
        except BaseException:
            shutil.rmtree(staged, ignore_errors=True)
            raise

        return Install(
            staging_dir=staged,
            fingerprint=RM.fingerprint(tree_dir),
            extras={
                "install_mode": "pi_root",
                "bridge_ext": str(bridge_path),
                **{k: v for k, v in ctx.items() if not k.startswith("file:")},
            },
        )

    def exec_argv(
        self,
        prompt: str,
        workspace: Path,
        model: str,
        *,
        effort: str = "high",
        harness_dir: Path | None = None,
    ) -> list[str]:
        """Construct the reference Pi CLI non-interactive JSON stream invocation."""
        binary = find_pi_binary()
        argv = [
            str(binary),
            "-p",
            prompt,
            "--mode",
            "json",
            "--no-session",
            "--tools",
            PI_BUILTIN_TOOLS,
        ]
        if model:
            if "/" in model:
                provider, bare_model = model.split("/", 1)
            else:
                provider, bare_model = api.PI_PROVIDER, model
            argv.extend(["--provider", provider, "--model", bare_model])
        if effort:
            argv.extend(["--thinking", effort])

        if harness_dir is not None:
            existing_bridge = Path(harness_dir) / "_pi_runtime" / "harness2_bridge.ts"
            if existing_bridge.is_file():
                argv.extend(["-e", str(existing_bridge)])
            elif _needs_bridge_extension(Path(harness_dir)):
                bridge = write_pi_bridge_extension(Path(harness_dir) / "_pi_runtime")
                argv.extend(["-e", str(bridge)])

        return argv

    def exec_env(
        self,
        base_env: Mapping[str, str],
        *,
        workspace: Path | None = None,
        model: str = "",
        agent_dir: Path | None = None,
    ) -> dict[str, str]:
        """Build the execution environment for Pi Coding Agent."""
        env = dict(base_env)
        env.setdefault("PI_OFFLINE", "1")
        env.setdefault("PI_SKIP_VERSION_CHECK", "1")
        env.setdefault("PI_TELEMETRY", "0")

        endpoint = api.pi()
        if endpoint is not None:
            extra_models = [model] if model else []
            if config.SOLVER_MODEL_PI:
                extra_models.append(config.SOLVER_MODEL_PI)
            api.pi_env(endpoint, env, agent_dir=agent_dir, extra_models=extra_models)

        if model:
            bare_model = model.split("/", 1)[-1] if "/" in model else model
            provider = model.split("/", 1)[0] if "/" in model else api.PI_PROVIDER
            env.setdefault("SEC_AGENT_HARNESS2_PI_PROVIDER", provider)
            env.setdefault("SEC_AGENT_HARNESS2_PI_ACTIVE_MODEL", bare_model)

        env.setdefault("SEC_AGENT_HARNESS2_PI_BIN", str(find_pi_binary()))
        if workspace is not None:
            env.setdefault("SEC_AGENT_HARNESS2_PI_HARNESS_DIR", str(workspace))
            env.setdefault("SEC_AGENT_HARNESS2_WORKSPACE", str(workspace))
            env.setdefault("HARNESS2_WORKSPACE", str(workspace))
        return env

    def execute(
        self, task_ref: str, install: Install, run_ids: list[str], timeout: int
    ) -> list[Path]:
        if self._launcher is None:
            raise RuntimeError(
                "PiSubstrate was constructed without a launcher body; the benchmark "
                "adapter must supply one"
            )
        return self._launcher(
            RunRequest(task_ref=task_ref, run_ids=tuple(run_ids), timeout=int(timeout)), install
        )

    def read_trajectory(
        self, stream_path: Path, *, obs_trunc: int, max_chars: int, args_trunc: int = 2000
    ) -> str:
        return render_events(
            Path(stream_path), obs_trunc=obs_trunc, max_chars=max_chars, args_trunc=args_trunc
        )

    def preflight(self) -> None:
        """Check the Pi CLI binary availability and basic operational health."""
        binary = find_pi_binary()
        if not binary.is_file() or not os.access(binary, os.X_OK):
            raise RuntimeError(
                f"Pi Coding Agent is not installed at {binary}; "
                "run 'harness2 setup <benchmark> --substrate pi' to install the project-level substrate."
            )
        want = getattr(config, "PI_VERSION", "")
        if want:
            try:
                r = subprocess.run(
                    [str(binary), "--version"],
                    capture_output=True,
                    text=True,
                    timeout=60,
                )
                if want not in (r.stdout or ""):
                    raise RuntimeError(
                        f"pi at {binary} reports {r.stdout.strip()!r}, pinned "
                        f"PI_VERSION is {want}; rerun "
                        "'harness2 setup <benchmark> --substrate pi' to repin."
                    )
            except OSError as exc:
                raise RuntimeError(f"could not probe pi version: {exc}") from exc


def parse_items(stream_path: Path, *, args_trunc: int = 2000) -> list[dict]:
    """Parse Pi `--mode json` JSONL stream into normalized trajectory items."""
    if not stream_path.is_file():
        return []

    items: list[dict] = []
    last_assistant_text = ""

    with open(stream_path, encoding="utf-8", errors="replace") as f:
        for raw_line in f:
            line = raw_line.strip()
            if not line or not line.startswith("{"):
                continue
            try:
                ev = json.loads(line)
            except json.JSONDecodeError:
                continue

            ev_type = ev.get("type", "")
            if ev_type == "message_end":
                msg = ev.get("message") or {}
                role = msg.get("role", "")
                if role != "assistant":
                    continue
                content = msg.get("content") or []
                if isinstance(content, list):
                    for block in content:
                        if not isinstance(block, dict):
                            continue
                        btype = block.get("type", "")
                        if btype == "thinking":
                            thinking = (block.get("thinking") or "").strip()
                            if thinking:
                                items.append({"kind": "thinking", "text": thinking})
                        elif btype == "text":
                            text = (block.get("text") or "").strip()
                            if text:
                                last_assistant_text = text
                                items.append({"kind": "assistant", "text": text})
                        elif btype in ("toolCall", "tool_use"):
                            tname = block.get("name", "unknown_tool")
                            tinput = block.get("arguments")
                            if tinput is None:
                                tinput = block.get("input", {})
                            summary = _summarize_tool_input(tname, tinput, args_trunc=args_trunc)
                            items.append({"kind": "action", "name": tname, "summary": summary})

                stop_reason = msg.get("stopReason", "")
                err_msg = (msg.get("errorMessage") or "").strip()
                if stop_reason == "error" or err_msg:
                    items.append(
                        {
                            "kind": "error",
                            "text": err_msg or f"Assistant message ended with stopReason={stop_reason}",
                        }
                    )

                usage = msg.get("usage") or {}
                if isinstance(usage, dict) and (
                    usage.get("input") is not None or usage.get("output") is not None
                ):
                    in_tok = usage.get("input", 0)
                    out_tok = usage.get("output", 0)
                    cache_read = usage.get("cacheRead", 0)
                    cost_obj = usage.get("cost") or {}
                    cost_total = cost_obj.get("total", 0.0) if isinstance(cost_obj, dict) else 0.0
                    items.append(
                        {
                            "kind": "usage",
                            "in_tok": in_tok,
                            "out_tok": out_tok,
                            "cache_read": cache_read,
                            "cost": cost_total,
                        }
                    )

            elif ev_type == "tool_execution_end":
                tool_name = ev.get("toolName", "")
                is_err = bool(ev.get("isError", False))
                result_obj = ev.get("result") or {}
                blocks = result_obj.get("content") if isinstance(result_obj, dict) else []
                texts: list[str] = []
                if isinstance(blocks, list):
                    for b in blocks:
                        if isinstance(b, dict) and b.get("type") == "text":
                            texts.append(str(b.get("text", "")))
                obs_text = "\n".join(t for t in texts if t).strip()
                if not obs_text and isinstance(result_obj, str):
                    obs_text = result_obj.strip()
                items.append(
                    {
                        "kind": "observation",
                        "tool_name": tool_name,
                        "is_error": is_err,
                        "text": obs_text,
                    }
                )

            elif ev_type == "auto_retry_start":
                attempt = ev.get("attempt", 1)
                max_attempts = ev.get("maxAttempts", 1)
                err_msg = ev.get("errorMessage", "")
                items.append(
                    {
                        "kind": "retry",
                        "text": f"auto_retry {attempt}/{max_attempts}: {err_msg}".strip(),
                    }
                )

            elif ev_type == "error":
                items.append(
                    {
                        "kind": "error",
                        "text": str(ev.get("message") or ev.get("error") or ev),
                    }
                )

    if last_assistant_text:
        items.append({"kind": "deliverable", "text": last_assistant_text})

    return items


def render_events(
    stream_path: Path,
    *,
    obs_trunc: int = 5000,
    max_chars: int = 90_000,
    args_trunc: int = 2000,
) -> str:
    """Render Pi `--mode json` JSONL stream into compact trajectory tags for the improver."""
    items = parse_items(stream_path, args_trunc=args_trunc)
    if not items:
        return ""

    chunks: list[str] = []
    for item in items:
        kind = item["kind"]
        if kind == "thinking":
            chunks.append(f"[THINKING] {item['text']}")
        elif kind == "assistant":
            chunks.append(f"[ASSISTANT] {item['text']}")
        elif kind == "action":
            chunks.append(f"[ACTION] {item['name']}: {item['summary']}")
        elif kind == "observation":
            obs_text = item["text"]
            if len(obs_text) > obs_trunc:
                obs_text = obs_text[:obs_trunc] + f"\n... [truncated {len(obs_text) - obs_trunc} chars]"
            prefix = "[OBSERVATION ERROR]" if item.get("is_error") else "[OBSERVATION]"
            chunks.append(f"{prefix} {obs_text}")
        elif kind == "usage":
            cost_str = f" cost=${item['cost']:.4f}" if item.get("cost") else ""
            chunks.append(
                f"[HARNESS] turn completed | tokens in={item['in_tok']} "
                f"out={item['out_tok']} cache_read={item['cache_read']}{cost_str}"
            )
        elif kind == "retry":
            chunks.append(f"[HARNESS] {item['text']}")
        elif kind == "error":
            chunks.append(f"[ERROR] {item['text']}")
        elif kind == "deliverable":
            chunks.append(f"[DELIVERABLE] {item['text']}")

    rendered = "\n\n".join(chunks).strip()
    if not rendered:
        return ""
    if len(rendered) > max_chars:
        dropped = len(rendered) - max_chars
        rendered = rendered[:max_chars] + f"\n…(+{dropped} chars — render truncation)"
    return rendered


def final_message(stream_path: Path) -> str:
    """Extract the final assistant deliverable text from a Pi JSONL stream."""
    for item in reversed(parse_items(stream_path)):
        if item["kind"] in ("deliverable", "assistant") and item.get("text"):
            return str(item["text"])
    return ""


def _summarize_tool_input(tool_name: str, tool_input: object, *, args_trunc: int = 2000) -> str:
    if not isinstance(tool_input, dict):
        return str(tool_input)[:args_trunc]
    lower = tool_name.lower()
    if lower == "bash" and "command" in tool_input:
        return str(tool_input["command"])[:args_trunc]
    if lower in ("read", "write", "edit"):
        p = tool_input.get("path") or tool_input.get("file_path")
        if p:
            return str(p)[:args_trunc]
    if lower == "subagent":
        return f"agent={tool_input.get('agent', '')} task={str(tool_input.get('task', ''))[:args_trunc]}"
    return json.dumps(tool_input, ensure_ascii=False)[:args_trunc]
